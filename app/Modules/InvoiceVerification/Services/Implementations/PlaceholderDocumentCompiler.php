<?php

namespace App\Modules\InvoiceVerification\Services\Implementations;

use App\Modules\InvoiceVerification\Domain\Models\Transaction;
use App\Modules\InvoiceVerification\Services\Contracts\DocumentCompiler;
use Illuminate\Support\Str;

class PlaceholderDocumentCompiler implements DocumentCompiler
{
    public function compileTemporary(Transaction $transaction, array $documents): array
    {
        $fileName = sprintf('kompilasi-%s.pdf', Str::slug($transaction->registration_number));
        $temporaryPath = tempnam(sys_get_temp_dir(), 'iv_compiled_test_');

        $content = [
            'message' => 'Temporary placeholder generated by compile adapter.',
            'transaction_id' => $transaction->id,
            'registration_number' => $transaction->registration_number,
            'compiled_at' => now()->toIso8601String(),
            'documents' => $documents,
        ];

        file_put_contents($temporaryPath, json_encode($content, JSON_PRETTY_PRINT));

        return [
            'file_name' => $fileName,
            'temporary_path' => $temporaryPath,
            'total_files' => count($documents),
        ];
    }
}
